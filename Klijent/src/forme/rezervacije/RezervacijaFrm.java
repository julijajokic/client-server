    private void napuniCmbKlijenti() throws Exception {
        List<Klijent> klijenti = new ArrayList<>();

        KlijentTransfer kt = new KlijentTransfer();
        kt.setOperacija(Konstante.VRATI_KLIJENTE);

        Komunikacija.getInstance().sendRequest(kt);

        ServerTransfer st = Komunikacija.getInstance().readResponse();
        if (st.getUspesnost() == Konstante.USPEH) {
            klijenti = (List<Klijent>) st.getPodaci();

            for (Klijent klijent : klijenti) {
                jcmbKlijenti.addItem(klijent);
            }
        }
    }

    private void napuniTabelu() throws Exception  {
        try {
            List<Rezervacija> rezervacije = new ArrayList<>();
            KlijentTransfer kt = new KlijentTransfer();
            kt.setOperacija(Konstante.VRATI_KLIJENTSKE_REZERVACIJE);
            kt.setParametar((Klijent) jcmbKlijenti.getSelectedItem());

            Komunikacija.getInstance().sendRequest(kt);

            ServerTransfer st = Komunikacija.getInstance().readResponse();
            
            if (st.getUspesnost() == Konstante.USPEH) {
              
                rezervacije = (List<Rezervacija>) st.getPodaci();
              
              
        
              
            
          
                PrikaziRezTableModel model = new PrikaziRezTableModel(rezervacije);
                jtblRezervacije.setModel(model);
                
               } else {
                Exception exi = st.getException();
                throw exi;

            }
        
            
    
            
            
               } catch (ClassNotFoundException ex) { 
       
            Logger.getLogger(RezervacijaFrm.class.getName()).log(Level.SEVERE, null, ex);

        } catch (IOException ex) {
            Logger.getLogger(RezervacijaFrm.class.getName()).log(Level.SEVERE, null, ex);
        
        } 
    }
    

