    private void btnSacuvajIzmeneActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajIzmeneActionPerformed
  if (!validirajFormu()) {
            JOptionPane.showMessageDialog(this, "Ne moze se izmeniti rezervacija");
            return;
        }
   PrikaziRezTableModel prtm = (PrikaziRezTableModel) jtblRezervacije.getModel();
        
        rez = prtm.getRezervacije().get(jtblRezervacije.getSelectedRow());
      if(sdf.format(rez.getDatum()).equals(jtxtDatumRezervisanja.getText())&&sdf.format(rez.getRokPlacanja()).equals(jtxtRokPlacanja.getText())&&String.valueOf(rez.getAvans()).equals(jtxtAvans.getText())&&String.valueOf(rez.getZaduzenje()).equals((jtxtZaduzenje.getText()))) {
        JOptionPane.showMessageDialog(this, "Niste nista izmenili");
      
      }
      else {
        Calendar cal1 = Calendar.getInstance();
        Calendar cal2 = Calendar.getInstance();
        try {
            cal1.setTime(sdf.parse(jtxtDatumRezervisanja.getText()));
            // cal1.add(Calendar.DAY_OF_YEAR, 0);
        } catch (ParseException ex) {
            Logger.getLogger(RezervacijaFrm.class.getName()).log(Level.SEVERE, null, ex);
        }
        rez.getKlijent().setKlijentID(Integer.parseInt(jtxtKlijentID.getText()));
         rez.getAranzman().setAranzmanID(Integer.parseInt(jtxtArazmanID.getText()));
        rez.setDatum(new java.sql.Date((cal1.getTime()).getTime()));

        try {
            cal2.setTime(sdf.parse(jtxtRokPlacanja.getText()));
         
        } catch (ParseException ex) {
            Logger.getLogger(RezervacijaFrm.class.getName()).log(Level.SEVERE, null, ex);
        }

        rez.setRokPlacanja(new java.sql.Date((cal2.getTime()).getTime()));

        rez.setAvans(Double.parseDouble(jtxtAvans.getText()));
        rez.setZaduzenje(Double.parseDouble(jtxtZaduzenje.getText()));

        try {
            KlijentTransfer kt = new KlijentTransfer();

          
            kt.setOperacija(Konstante.IZMENI_REZERVACIJU);
            kt.setParametar(rez);

            Komunikacija.getInstance().sendRequest(kt);

            ServerTransfer st = Komunikacija.getInstance().readResponse();
            if (st.getUspesnost() == Konstante.USPEH) {
                JOptionPane.showMessageDialog(this, "Rezervacija uspesno izmenjena!");
                return;
            }

        } catch (ClassNotFoundException | IOException ex) {
            Logger.getLogger(RezervacijaFrm.class.getName()).log(Level.SEVERE, null, ex);
        } catch (NumberFormatException exi) {
            JOptionPane.showMessageDialog(this, "Greska pri menjanju");
        }

      }
    }//GEN-LAST:event_btnSacuvajIzmeneActionPerformed

