    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed
        try {
          
            if (jtblRezervacije.getSelectedRow() == -1) {
                JOptionPane.showMessageDialog(this, "Morate selektovati rezervaciju!");
                return;
            }
  PrikaziRezTableModel prtm = (PrikaziRezTableModel) jtblRezervacije.getModel();
            Rezervacija rez = prtm.getRezervacije().get(jtblRezervacije.getSelectedRow());
            KlijentTransfer kt = new KlijentTransfer();
            kt.setParametar(rez);
            kt.setOperacija(Konstante.OBRISI_REZERVACIJU);
        

            Komunikacija.getInstance().sendRequest(kt);

            ServerTransfer st = Komunikacija.getInstance().readResponse();
            if (st.getUspesnost() == Konstante.USPEH) {

                JOptionPane.showMessageDialog(this, "Rezervacija uspesno obrisana");
                prtm.getRezervacije().remove(rez);
                prtm.fireTableDataChanged();

            } else {
                JOptionPane.showMessageDialog(this, "Rezervacija nije obrisana. Greska: " + st.getException());
            }

        } catch (ClassNotFoundException | IOException ex) {
            Logger.getLogger(RezervacijaFrm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnObrisiActionPerformed

