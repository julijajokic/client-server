    private void btnKrerirajRezervacijuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnKrerirajRezervacijuActionPerformed
        if (!validirajFormu()) {
            JOptionPane.showMessageDialog(this, "Ne moze se izmeniti rezervacija");
            return;
        }

        r = new Rezervacija();

        r.setKlijent(k);

        r.setRezervacijaID(Integer.parseInt(jtxtRezervacijaID.getText()));
        Aranzman ar = (Aranzman) jcbAranzman.getSelectedItem();
        try {

            r.setRokPlacanja(new java.sql.Date(sdf.parse(jtxtRokPlacanja.getText()).getTime()));
        } catch (ParseException ex) {
            Logger.getLogger(DodajRezervacijuPanel.class.getName()).log(Level.SEVERE, null, ex);
        }
        r.setAranzman(ar);

        r.setDatum(new java.sql.Date((new Date()).getTime()));
        // r.setRokPlacanja(new java.sql.Date((cal.getTime()).getTime()));

        try {
            Double avans = Double.parseDouble(jtxtAvans.getText().trim());
            r.setAvans(avans);
            r.setZaduzenje(r.getAranzman().getCena() - r.getAvans());
            jtxtZaduzenje.setText("" + r.getZaduzenje());
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Unesite broj!");
        }

        r.setAgent((Agent) Sesija.vratiInstancu().getMapa().get("agent"));
        if (dodajRezervaciju(r) == true) {
            Window w = SwingUtilities.getWindowAncestor(this);
            w.setVisible(false);
        } else {
            JOptionPane.showMessageDialog(this, "Neuspesno kreiranje rezervacije");
        }

    }//GEN-LAST:event_btnKrerirajRezervacijuActionPerformed

