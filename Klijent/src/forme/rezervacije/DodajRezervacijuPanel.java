    private void srediFormu() {
        jcbAranzman.removeAllItems();
        List<Aranzman> lista = vratiAranzmane();
        for (Aranzman aranzman : lista) {
            jcbAranzman.addItem(aranzman);
        }
        jcbAranzman.setSelectedIndex(-1);

    }

    private List<Aranzman> vratiAranzmane() {
        List<Aranzman> listaar = new LinkedList<>();
        try {

            listaar = Kontroler.getInstance().getAranzmane();
        } catch (Exception ex) {
            Logger.getLogger(DodajRezervacijuPanel.class.getName()).log(Level.SEVERE, null, ex);
        }
        return listaar;

    }

    private boolean dodajRezervaciju(Rezervacija r) {
        try {
            boolean kreiran = Kontroler.getInstance().kreirajRezervaciju(r);

            if (kreiran == true) {
                JOptionPane.showMessageDialog(this, "Uspesno kreirana rezervacija za klijenta: " + r.getKlijent().getIme() + " " + r.getKlijent().getPrezime());
                return true;
            }
        } catch (Exception ex) {
            Logger.getLogger(DodajRezervacijuPanel.class.getName()).log(Level.SEVERE, null, ex);
        }
        return false;
    }

    private boolean validirajFormu() {
        List<JTextField> textFields = new LinkedList<>();
        boolean valid = true;

        textFields.add(jtxtKlijentID);
        textFields.add(jtxtRezervacijaID);
        textFields.add(jtxtDatumRezervisanja);
        textFields.add(jtxtRokPlacanja);
        textFields.add(jtxtAvans);
        textFields.add(jtxtZaduzenje);
        for (JTextField field : textFields) {
            if (field.getText().isEmpty()) {
                valid = false;
                field.setBorder(BorderFactory.createLineBorder(Color.RED));
            }
        }
        if (jcbAranzman.getSelectedIndex() == -1) {
            valid = false;
            jcbAranzman.setBorder(BorderFactory.createLineBorder(Color.RED));
        }

        return valid;
    }

    private void odrediIdRezervacije() {

        try {

            List<Rezervacija> listrezervacija = Kontroler.getInstance().getKlijentskeRezervacije(k);
            if (listrezervacija.size()==0) {
                int rezervacijaid = k.getKlijentID() * 10 + 1;
                jtxtRezervacijaID.setText(rezervacijaid + "");
                jtxtRezervacijaID.setEditable(false);
            } else {
                int rezervacijaid = listrezervacija.get(listrezervacija.size() - 1).getRezervacijaID() + 1;
                jtxtRezervacijaID.setText(rezervacijaid + "");
                jtxtRezervacijaID.setEditable(false);
            }
        } catch (Exception ex) {
            Logger.getLogger(DodajKlijentaPanel.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    private void postaviKlijentID() {
        jtxtKlijentID.setText(k.getKlijentID() + "");
        jtxtKlijentID.setEditable(false);
    }
