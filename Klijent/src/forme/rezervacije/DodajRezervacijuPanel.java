    private void jcbAranzmanItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jcbAranzmanItemStateChanged
        if (jcbAranzman.getSelectedIndex() == -1) {
            jtxtRokPlacanja.setText("");
        } else {
            Aranzman aranzman = (Aranzman) jcbAranzman.getSelectedItem();

            SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy.");

            Calendar cal = Calendar.getInstance();
            cal.setTime(aranzman.getDatumPolaska());
            cal.add(Calendar.DAY_OF_YEAR, -1);
            jtxtRokPlacanja.setText(sdf.format(cal.getTime().getTime()));
        }
    }//GEN-LAST:event_jcbAranzmanItemStateChanged

