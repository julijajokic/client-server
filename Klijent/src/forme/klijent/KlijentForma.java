    private void jbtnSacuvajIzmeneActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnSacuvajIzmeneActionPerformed
 
        
        
        if (!validirajFormu()) {
            JOptionPane.showMessageDialog(this, "Klijenta nije moguce izmeniti!");
            return;
        }
        
        
        KlijentiTableModel ktm = (KlijentiTableModel) jtblKlijenti.getModel();
        
       Klijent klijent = ktm.getKlijenti().get(jtblKlijenti.getSelectedRow());
        if(klijent.getIme().equals(jtxtUnosIme.getText())&&klijent.getPrezime().equals(jtxtPrezime.getText())&&klijent.getEmail().equals(jtxtUnosEmail.getText())&&klijent.getTelefon().equals(jtxtUnosTelefon.getText())&&klijent.getMesto().equals(jcmbUnosMesto.getSelectedItem())){
            JOptionPane.showMessageDialog(this, "Niste nista izmenili.");
        }
        else {
           
          klijent.setIme(jtxtUnosIme.getText());
           klijent.setPrezime(jtxtPrezime.getText());
           klijent.setEmail(jtxtUnosEmail.getText());
          klijent.setTelefon(jtxtUnosTelefon.getText());
          
          klijent.setMesto((Mesto) jcmbUnosMesto.getSelectedItem());
          
         
                  try{
            KlijentTransfer kt = new KlijentTransfer();
            kt.setOperacija(Konstante.IZMENI_KLIJENTA);
            kt.setParametar(klijent);
            Komunikacija.getInstance().sendRequest(kt);
            ServerTransfer st = Komunikacija.getInstance().readResponse();
            if (st.getUspesnost() == Konstante.USPEH) {
                JOptionPane.showMessageDialog(this, "Klijent uspesno izmenjen!");
                ktm.fireTableDataChanged();
                return;
            }
            else {
                
                JOptionPane.showMessageDialog(this, "Greska pri menjanju");
            }
            
        } catch (ClassNotFoundException | IOException ex) {
            Logger.getLogger(KlijentForma.class.getName()).log(Level.SEVERE, null, ex);
        }
        }
    }//GEN-LAST:event_jbtnSacuvajIzmeneActionPerformed

