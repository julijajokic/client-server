    private void napuniCmb() throws Exception {
        List<PoslovniPartner> partneri = new ArrayList<>();

        KlijentTransfer kt = new KlijentTransfer();
        kt.setOperacija(Konstante.VRATI_PARTNERE);

        Komunikacija.getInstance().sendRequest(kt);

        ServerTransfer st = Komunikacija.getInstance().readResponse();
        if (st.getUspesnost() == Konstante.USPEH) {
            partneri = (List<PoslovniPartner>) st.getPodaci();

            for (PoslovniPartner poslovniPartner : partneri) {
                
            cmbPoslovniPartner.addItem(poslovniPartner);
            }
        }
    }

    private void napuniTabelu() throws Exception {
        try {
            List<Aranzman> aranzmani = new ArrayList<>();
            KlijentTransfer kt = new KlijentTransfer();
            kt.setOperacija(Konstante.VRATI_PARTNERSKE_ARANZMANE);
            kt.setParametar((PoslovniPartner) cmbPoslovniPartner.getSelectedItem());

            Komunikacija.getInstance().sendRequest(kt);

            ServerTransfer st = Komunikacija.getInstance().readResponse();
            if (st.getUspesnost() == Konstante.USPEH) {
               aranzmani = (List<Aranzman>) st.getPodaci();

                PrikaziAranzmanTableModel model = new PrikaziAranzmanTableModel(aranzmani);
               jtblAranzmani.setModel(model);
            } else {
                Exception exi = st.getException();
                throw exi;

            }
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(AranzmanFrm.class.getName()).log(Level.SEVERE, null, ex);

        } catch (IOException ex) {
            Logger.getLogger(AranzmanFrm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

