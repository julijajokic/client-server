    private void btnsacuvajIzmeneActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsacuvajIzmeneActionPerformed
       if (!validirajPolja()) {
            JOptionPane.showMessageDialog(this, "Nije moguce izmeniti aranzman");
            return;
        }
        
        
        PrikaziAranzmanTableModel patm =  (PrikaziAranzmanTableModel) jtblAranzmani.getModel();
        SimpleDateFormat  sdf = new SimpleDateFormat("dd.MM.yyyy.");
        aranzman = patm.getLista().get(jtblAranzmani.getSelectedRow());
        if(aranzman.getNaziv().equals(jtxtNaziv.getText())&&aranzman.getDestinacija().equals(jtxtDestinacija.getText())&&(sdf.format(aranzman.getDatumPolaska())).equals(jtxtDatumOd.getText())&& (sdf.format(aranzman.getDatumPovratka())).equals(jtxtDatumdo.getText())&&String.valueOf(aranzman.getCena()).equals(jtxtAranzmanCena.getText())){
            JOptionPane.showMessageDialog(this, "Niste nista izmenili");
        }
        else {
        aranzman.setNaziv(jtxtNaziv.getText());
        aranzman.setDestinacija(jtxtDestinacija.getText());
      
          
          try {
              aranzman.setDatumPolaska(new java.sql.Date(sdf.parse(jtxtDatumOd.getText()).getTime()));
          } catch (ParseException ex) {
              Logger.getLogger(AranzmanFrm.class.getName()).log(Level.SEVERE, null, ex);
          }
              
           
             
             
          try {
              aranzman.setDatumPovratka(new java.sql.Date((sdf.parse(jtxtDatumdo.getText())).getTime()));
          } catch (ParseException ex) {
              Logger.getLogger(AranzmanFrm.class.getName()).log(Level.SEVERE, null, ex);
          }
               aranzman.setCena(Double.parseDouble(jtxtAranzmanCena.getText()));
           
              
           
               
             try{
            KlijentTransfer kt = new KlijentTransfer();

            //uzeti podatke iz polja za izmenu i postaviti te podatke kao podatke klijenta
            kt.setOperacija(Konstante.IZMENI_ARANZMAN);
            kt.setParametar(aranzman);
           
                Komunikacija.getInstance().sendRequest(kt);
          
            ServerTransfer st = Komunikacija.getInstance().readResponse();
            if (st.getUspesnost() == Konstante.USPEH) {
                JOptionPane.showMessageDialog(this, "Aranzman uspesno izmenjena!");
              return;
            }
            

        } catch (ClassNotFoundException | IOException ex) {
            Logger.getLogger(AranzmanFrm.class.getName()).log(Level.SEVERE, null, ex);
 }catch(NumberFormatException exi){
            JOptionPane.showMessageDialog(this, "Greska pri menjanju");
        }
        }
    }//GEN-LAST:event_btnsacuvajIzmeneActionPerformed

