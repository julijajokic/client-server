    private boolean validirajFormu() {
           boolean valid =true;
        List<JTextField> textFields = new LinkedList<>();
         textFields.add(jtxtIzmenaPartnerID);
        textFields.add(jtxtIzmenaAdresaBroj);
        textFields.add(jtxtIzmenaMaticni);
        textFields.add(jtxtIzmenaNaziv);
        textFields.add(jtxtIzmenaPIB);
        textFields.add(jtxtIzmenaTip);
        textFields.add(jtxtIzmenaUlica);
        for (JTextField field : textFields) {
            if (field.getText().isEmpty()) {
                valid=false;
                field.setBorder(BorderFactory.createLineBorder(Color.RED));
                return valid;
            }
        }

        try {
            if (Integer.parseInt(jtxtIzmenaMaticni.getText().trim())<10000000 || Integer.parseInt(jtxtIzmenaMaticni.getText().trim())>99999999) {
                jtxtIzmenaMaticni.setBorder(BorderFactory.createLineBorder(Color.RED));
                jtxtIzmenaMaticni.setText("Uneti 8 cifara");
                valid=false;
            }
        } catch (Exception e) {
                jtxtIzmenaMaticni.setBorder(BorderFactory.createLineBorder(Color.RED));
                jtxtIzmenaMaticni.setText("greska u formatu");
                System.out.println(e.getMessage());
                valid=false;
        }
        try {
            if (Integer.parseInt(jtxtIzmenaPIB.getText().trim())<100000000 || Integer.parseInt(jtxtIzmenaPIB.getText().trim())>999999999) {
                jtxtIzmenaPIB.setBorder(BorderFactory.createLineBorder(Color.RED));
                jtxtIzmenaPIB.setText("Uneti 9 cifara");
                valid=false;
            }
        } catch (Exception e) {
                jtxtIzmenaPIB.setBorder(BorderFactory.createLineBorder(Color.RED));
                jtxtIzmenaPIB.setText("greska u formatu");
                System.out.println(e.getMessage());
                valid=false;
        }
        if (jcmbIzmenaPartnerMesto.getSelectedIndex()==-1) {
            valid=false;
            jcmbIzmenaPartnerMesto.setBorder(BorderFactory.createLineBorder(Color.RED));
        }
        
        return valid;
        
    }
    

   
